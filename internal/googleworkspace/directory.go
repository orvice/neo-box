// FieldError is rejected locally before any mutation is sent.
type FieldError struct{ Field, Message string }

func (e *FieldError) Error() string       { return e.Field + ": " + e.Message }
func invalid(field, message string) error { return &FieldError{field, message} }

type Alias struct {
	Email    string
	Editable bool
}

func (c *Client) ListAliases(ctx context.Context, userID string) ([]Alias, error) {
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return nil, err
	}
	var result struct {
		Aliases []struct {
			Alias string `json:"alias"`
		} `json:"aliases"`
	}
	if err = c.do(ctx, http.MethodGet, "/users/"+url.PathEscape(u.ID)+"/aliases", nil, nil, &result); err != nil {
		return nil, err
	}
	// Directory's alias list contains manually managed aliases; nonEditableAliases
	// are returned on the user, for example aliases generated by domain aliases.
	var raw struct {
		NonEditableAliases []string `json:"nonEditableAliases"`
	}
	if err = c.do(ctx, http.MethodGet, "/users/"+url.PathEscape(u.ID), nil, nil, &raw); err != nil {
		return nil, err
	}
	out := make([]Alias, 0, len(result.Aliases)+len(raw.NonEditableAliases))
	for _, a := range result.Aliases {
		out = append(out, Alias{Email: a.Alias, Editable: true})
	}
	for _, a := range raw.NonEditableAliases {
		out = append(out, Alias{Email: a, Editable: false})
	}
	return out, nil
}
func (c *Client) AddAlias(ctx context.Context, userID, email string) (*Alias, error) {
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return nil, err
	}
	if err = c.checkEmailDomain(ctx, email); err != nil {
		return nil, err
	}
	var a struct {
		Alias string `json:"alias"`
	}
	if err = c.do(ctx, http.MethodPost, "/users/"+url.PathEscape(u.ID)+"/aliases", nil, map[string]string{"alias": email}, &a); err != nil {
		return nil, err
	}
	return &Alias{Email: a.Alias, Editable: true}, nil
}
func (c *Client) DeleteAlias(ctx context.Context, userID, email string) error {
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return err
	}
	aliases, err := c.ListAliases(ctx, u.ID)
	if err != nil {
		return err
	}
	editable := false
	for _, a := range aliases {
		if strings.EqualFold(a.Email, email) && a.Editable {
			editable = true
		}
	}
	if !editable {
		return invalid("alias", "only an existing editable alias can be removed")
	}
	return c.do(ctx, http.MethodDelete, "/users/"+url.PathEscape(u.ID)+"/aliases/"+url.PathEscape(email), nil, nil, nil)
}
func (c *Client) checkEmailDomain(ctx context.Context, email string) error {
	if !ValidEmail(email) {
		return invalid("email", "must be a valid email address")
	}
	domain := strings.Split(email, "@")[1]
	var result struct {
		Domains []struct {
			DomainName string `json:"domainName"`
			Verified   bool   `json:"verified"`
		} `json:"domains"`
	}
	if err := c.do(ctx, http.MethodGet, "/customer/"+url.PathEscape(c.CustomerID)+"/domains", nil, nil, &result); err != nil {
		return err
	}
	for _, d := range result.Domains {
		if strings.EqualFold(d.DomainName, domain) && d.Verified {
			return nil
		}
	}
	return ErrTenantMismatch
}

type Group struct {
	ID                 string `json:"id"`
	Email              string `json:"email"`
	Name               string `json:"name"`
	Description        string `json:"description"`
	DirectMembersCount string `json:"directMembersCount"`
}
type GroupPage struct {
	Groups        []Group `json:"groups"`
	NextPageToken string  `json:"nextPageToken"`
}
type Member struct {
	ID     string `json:"id"`
	Email  string `json:"email"`
	Role   string `json:"role"`
	Type   string `json:"type"`
	Status string `json:"status"`
}
type MemberPage struct {
	Members       []Member `json:"members"`
	NextPageToken string   `json:"nextPageToken"`
}

func (c *Client) ListGroups(ctx context.Context, query, token string, size int) (*GroupPage, error) {
	q := url.Values{"customer": {c.CustomerID}, "maxResults": {fmt.Sprint(size)}, "orderBy": {"email"}}
	if query != "" {
		q.Set("query", query)
	}
	if token != "" {
		q.Set("pageToken", token)
	}
	var p GroupPage
	if err := c.do(ctx, http.MethodGet, "/groups", q, nil, &p); err != nil {
		return nil, err
	}
	return &p, nil
}

// GetGroup checks membership in the explicit customer's paged group list.
// A global groups.get alone cannot prove ownership: Group has no customerId.
func (c *Client) GetGroup(ctx context.Context, key string) (*Group, error) {
	if strings.TrimSpace(key) == "" {
		return nil, invalid("group_id", "is required")
	}
	token := ""
	seen := map[string]bool{}
	for {
		page, err := c.ListGroups(ctx, "", token, 200)
		if err != nil {
			return nil, err
		}
		for _, g := range page.Groups {
			if g.ID == key || strings.EqualFold(g.Email, key) {
				return &g, nil
			}
		}
		if page.NextPageToken == "" {
			return nil, ErrTenantMismatch
		}
		if seen[page.NextPageToken] {
			return nil, fmt.Errorf("Google repeated a group page token")
		}
		seen[page.NextPageToken] = true
		token = page.NextPageToken
	}
}
func groupBody(email, name, description string) (map[string]string, error) {
	if !ValidEmail(email) {
		return nil, invalid("email", "must be a valid email address")
	}
	if strings.TrimSpace(name) == "" {
		return nil, invalid("name", "is required")
	}
	return map[string]string{"email": email, "name": name, "description": description}, nil
}
func (c *Client) CreateGroup(ctx context.Context, email, name, description string) (*Group, error) {
	body, err := groupBody(email, name, description)
	if err != nil {
		return nil, err
	}
	if err = c.checkEmailDomain(ctx, email); err != nil {
		return nil, err
	}
	var g Group
	if err = c.do(ctx, http.MethodPost, "/groups", nil, body, &g); err != nil {
		return nil, err
	}
	return &g, nil
}
func (c *Client) UpdateGroup(ctx context.Context, id, email, name, description string) (*Group, error) {
	g, err := c.GetGroup(ctx, id)
	if err != nil {
		return nil, err
	}
	body, err := groupBody(email, name, description)
	if err != nil {
		return nil, err
	}
	if err = c.checkEmailDomain(ctx, email); err != nil {
		return nil, err
	}
	var out Group
	if err = c.do(ctx, http.MethodPatch, "/groups/"+url.PathEscape(g.ID), nil, body, &out); err != nil {
		return nil, err
	}
	return &out, nil
}
func (c *Client) DeleteGroup(ctx context.Context, id string) error {
	g, err := c.GetGroup(ctx, id)
	if err != nil {
		return err
	}
	return c.do(ctx, http.MethodDelete, "/groups/"+url.PathEscape(g.ID), nil, nil, nil)
}
func (c *Client) ListUserGroups(ctx context.Context, userID string) ([]Group, error) {
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return nil, err
	}
	// userKey and customer cannot be combined. Intersect the user's memberships
	// with the selected customer's group IDs before exposing them.
	own := map[string]Group{}
	token := ""
	seen := map[string]bool{}
	for {
		p, err := c.ListGroups(ctx, "", token, 200)
		if err != nil {
			return nil, err
		}
		for _, g := range p.Groups {
			own[g.ID] = g
		}
		if p.NextPageToken == "" {
			break
		}
		if seen[p.NextPageToken] {
			return nil, fmt.Errorf("Google repeated a group page token")
		}
		seen[p.NextPageToken] = true
		token = p.NextPageToken
	}
	out := []Group{}
	token = ""
	seen = map[string]bool{}
	for {
		q := url.Values{"userKey": {u.ID}, "maxResults": {"200"}}
		if token != "" {
			q.Set("pageToken", token)
		}
		var p GroupPage
		if err = c.do(ctx, http.MethodGet, "/groups", q, nil, &p); err != nil {
			return nil, err
		}
		for _, g := range p.Groups {
			if o, ok := own[g.ID]; ok {
				out = append(out, o)
			}
		}
		if p.NextPageToken == "" {
			break
		}
		if seen[p.NextPageToken] {
			return nil, fmt.Errorf("Google repeated a group page token")
		}
		seen[p.NextPageToken] = true
		token = p.NextPageToken
	}
	return out, nil
}
func (c *Client) ListMembers(ctx context.Context, groupID, token string, size int) (*MemberPage, error) {
	g, err := c.GetGroup(ctx, groupID)
	if err != nil {
		return nil, err
	}
	q := url.Values{"maxResults": {fmt.Sprint(size)}, "includeDerivedMembership": {"false"}}
	if token != "" {
		q.Set("pageToken", token)
	}
	var p MemberPage
	if err = c.do(ctx, http.MethodGet, "/groups/"+url.PathEscape(g.ID)+"/members", q, nil, &p); err != nil {
		return nil, err
	}
	return &p, nil
}
func memberRole(role string) error {
	switch role {
	case "OWNER", "MANAGER", "MEMBER":
		return nil
	}
	return invalid("role", "must be OWNER, MANAGER or MEMBER")
}
func (c *Client) AddMember(ctx context.Context, groupID, email, role string) (*Member, error) {
	if !ValidEmail(email) {
		return nil, invalid("email", "must be a valid member email")
	}
	if err := memberRole(role); err != nil {
		return nil, err
	}
	g, err := c.GetGroup(ctx, groupID)
	if err != nil {
		return nil, err
	}
	// External members are intentional and still restricted to an owned group.
	var m Member
	if err = c.do(ctx, http.MethodPost, "/groups/"+url.PathEscape(g.ID)+"/members", nil, map[string]string{"email": email, "role": role}, &m); err != nil {
		return nil, err
	}
	return &m, nil
}
func (c *Client) member(ctx context.Context, groupID, key string) (*Group, *Member, error) {
	if strings.TrimSpace(key) == "" {
		return nil, nil, invalid("member_id", "is required")
	}
	g, err := c.GetGroup(ctx, groupID)
	if err != nil {
		return nil, nil, err
	}
	var m Member
	if err = c.do(ctx, http.MethodGet, "/groups/"+url.PathEscape(g.ID)+"/members/"+url.PathEscape(key), nil, nil, &m); err != nil {
		return nil, nil, err
	}
	if m.ID == "" {
		return nil, nil, fmt.Errorf("Google did not return a member ID")
	}
	return g, &m, nil
}
func (c *Client) UpdateMember(ctx context.Context, groupID, key, role string) (*Member, error) {
	if err := memberRole(role); err != nil {
		return nil, err
	}
	g, m, err := c.member(ctx, groupID, key)
	if err != nil {
		return nil, err
	}
	var out Member
	if err = c.do(ctx, http.MethodPatch, "/groups/"+url.PathEscape(g.ID)+"/members/"+url.PathEscape(m.ID), nil, map[string]string{"role": role}, &out); err != nil {
		return nil, err
	}
	return &out, nil
}
func (c *Client) DeleteMember(ctx context.Context, groupID, key string) error {
	g, m, err := c.member(ctx, groupID, key)
	if err != nil {
		return err
	}
	return c.do(ctx, http.MethodDelete, "/groups/"+url.PathEscape(g.ID)+"/members/"+url.PathEscape(m.ID), nil, nil, nil)
}

type OrgUnit struct {
	ID          string `json:"orgUnitId"`
	Name        string `json:"name"`
	Description string `json:"description"`
	Path        string `json:"orgUnitPath"`
	ParentPath  string `json:"parentOrgUnitPath"`
}

func (c *Client) orgUnitsPath() string {
	return "/customer/" + url.PathEscape(c.CustomerID) + "/orgunits"
}
func (c *Client) ListOrgUnits(ctx context.Context) ([]OrgUnit, error) {
	var result struct {
		Units []OrgUnit `json:"organizationUnits"`
	}
	if err := c.do(ctx, http.MethodGet, c.orgUnitsPath(), url.Values{"orgUnitPath": {"/"}, "type": {"all"}}, nil, &result); err != nil {
		return nil, err
	}
	return result.Units, nil
}
func ValidOrgUnitName(name string) bool {
	if strings.TrimSpace(name) == "" || name == "." || name == ".." || strings.Contains(name, "/") {
		return false
	}
	for _, r := range name {
		if unicode.IsControl(r) {
			return false
		}
	}
	return true
}
func ValidOrgUnitPath(path string) bool {
	if path == "/" {
		return true
	}
	if !strings.HasPrefix(path, "/") || strings.HasSuffix(path, "/") {
		return false
	}
	for _, part := range strings.Split(path[1:], "/") {
		if !ValidOrgUnitName(part) {
			return false
		}
	}
	return true
}
func (c *Client) orgUnit(ctx context.Context, id string) (*OrgUnit, error) {
	if strings.TrimSpace(id) == "" {
		return nil, invalid("org_unit_id", "is required; the root cannot be edited or deleted")
	}
	units, err := c.ListOrgUnits(ctx)
	if err != nil {
		return nil, err
	}
	for _, o := range units {
		if o.ID == id && o.Path != "/" {
			return &o, nil
		}
	}
	return nil, ErrTenantMismatch
}
func (c *Client) orgUnitBody(ctx context.Context, name, description, parent string, current *OrgUnit) (map[string]string, error) {
	if !ValidOrgUnitName(name) {
		return nil, invalid("name", "must be a nonempty name without / or control characters")
	}
	if parent == "" {
		parent = "/"
	}
	if !ValidOrgUnitPath(parent) {
		return nil, invalid("parent_path", "must be a valid absolute organization path")
	}
	if current != nil && (parent == current.Path || strings.HasPrefix(parent, current.Path+"/")) {
		return nil, invalid("parent_path", "an organizational unit cannot be moved inside itself")
	}
	if parent != "/" {
		units, err := c.ListOrgUnits(ctx)
		if err != nil {
			return nil, err
		}
		found := false
		for _, o := range units {
			if o.Path == parent {
				found = true
			}
		}
		if !found {
			return nil, ErrTenantMismatch
		}
	}
	return map[string]string{"name": name, "description": description, "parentOrgUnitPath": parent}, nil
}
func (c *Client) CreateOrgUnit(ctx context.Context, name, description, parent string) (*OrgUnit, error) {
	body, err := c.orgUnitBody(ctx, name, description, parent, nil)
	if err != nil {
		return nil, err
	}
	var o OrgUnit
	if err = c.do(ctx, http.MethodPost, c.orgUnitsPath(), nil, body, &o); err != nil {
		return nil, err
	}
	return &o, nil
}
func (c *Client) UpdateOrgUnit(ctx context.Context, id, name, description, parent string) (*OrgUnit, error) {
	old, err := c.orgUnit(ctx, id)
	if err != nil {
		return nil, err
	}
	body, err := c.orgUnitBody(ctx, name, description, parent, old)
	if err != nil {
		return nil, err
	}
	var o OrgUnit
	if err = c.do(ctx, http.MethodPatch, c.orgUnitsPath()+"/"+url.PathEscape(old.ID), nil, body, &o); err != nil {
		return nil, err
	}
	return &o, nil
}
func (c *Client) DeleteOrgUnit(ctx context.Context, id string) error {
	o, err := c.orgUnit(ctx, id)
	if err != nil {
		return err
	}
	return c.do(ctx, http.MethodDelete, c.orgUnitsPath()+"/"+url.PathEscape(o.ID), nil, nil, nil)
}

type UserToken struct {
	ClientID    string   `json:"clientId"`
	DisplayText string   `json:"displayText"`
	Scopes      []string `json:"scopes"`
	Anonymous   bool     `json:"anonymous"`
	NativeApp   bool     `json:"nativeApp"`
}

func (c *Client) SignOutUser(ctx context.Context, userID string) error {
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return err
	}
	return c.do(ctx, http.MethodPost, "/users/"+url.PathEscape(u.ID)+"/signOut", nil, nil, nil)
}
func (c *Client) ListUserTokens(ctx context.Context, userID string) ([]UserToken, error) {
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return nil, err
	}
	var result struct {
		Items []UserToken `json:"items"`
	}
	if err = c.do(ctx, http.MethodGet, "/users/"+url.PathEscape(u.ID)+"/tokens", nil, nil, &result); err != nil {
		return nil, err
	}
	return result.Items, nil
}
func (c *Client) RevokeUserToken(ctx context.Context, userID, clientID string) error {
	if strings.TrimSpace(clientID) == "" {
		return invalid("client_id", "is required")
	}
	u, err := c.GetUser(ctx, userID)
	if err != nil {
		return err
	}
	// Deleting an application's grant never returns or stores actual tokens.
	return c.do(ctx, http.MethodDelete, "/users/"+url.PathEscape(u.ID)+"/tokens/"+url.PathEscape(clientID), nil, nil, nil)
}
